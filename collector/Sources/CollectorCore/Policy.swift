import Foundation

/// 采集前的黑名单：命中的应用和窗口完全不采，只是结束当前段。
public enum CapturePolicy {
  public static let blockedBundles: Set<String> = [
    "com.apple.keychainaccess", "com.apple.Passwords",
    "me.proton.pass.electron", "com.1password.1password", "com.agilebits.onepassword7",
    "com.bitwarden.desktop", "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal",
  ]

  /// 浏览器隐私窗口的标题特征（各浏览器的写法不同）。
  public static let privateTitleMarkers = [
    "Private Browsing", "Private Window", "Incognito", "InPrivate",
    "隐私浏览", "无痕", "私密浏览", "隐身",
  ]

  public static func shouldSkip(bundleID: String, window: String, extraBlocked: Set<String> = []) -> Bool {
    if blockedBundles.contains(bundleID) || extraBlocked.contains(bundleID) { return true }
    return privateTitleMarkers.contains { window.localizedCaseInsensitiveContains($0) }
  }
}

/// 剪贴板：密码管理器复制时会打这些标记（nspasteboard.org 约定），带标记的不记。
public enum ClipboardPolicy {
  public static let skipTypes: Set<String> = [
    "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
  ]
  public static let imageTypes: Set<String> = ["public.png", "public.tiff", "public.jpeg", "public.heic"]
  public static let maxBody = 20_000

  public static func shouldSkip(types: [String]) -> Bool { types.contains { skipTypes.contains($0) } }

  public static func record(text: String?, types: [String], app: String?, time: Date, device: String) -> Record? {
    if shouldSkip(types: types) { return nil }
    let ctx = RecordContext(app: app)
    if let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
      let body = Text.capturePrefix(text, limit: maxBody)
      let first = Text.lines(text).first ?? ""
      return Record(device: device, source: "mac.clipboard", kind: "event", start: time, context: ctx,
                    title: "复制 · " + Text.capturePrefix(first.isEmpty ? "（无标题）" : first, limit: 79, suffix: "…"), body: body, capture: Capture(method: "api"))
    }
    if types.contains(where: { imageTypes.contains($0) }) {
      return Record(device: device, source: "mac.clipboard", kind: "event", start: time, context: ctx,
                    title: "复制了一张图片", body: "", capture: Capture(method: "api"))
    }
    return nil
  }
}

/// 有界发送窗口。HubClient 用加密 outbox 保存窗口以外的记录；存储失效时内存退路超限会计数。
public final class OutboundQueue {
  public let capacity: Int
  public private(set) var items: [Record] = []
  public private(set) var dropped = 0
  private var peak = 0
  private let lock = NSLock()

  public init(capacity: Int = 5000) { self.capacity = capacity }

  public func push(_ records: [Record]) {
    lock.lock(); defer { lock.unlock() }
    items += records
    if items.count > capacity {
      let n = items.count - capacity
      dropped += n
      items.removeFirst(n)
    }
    peak = max(peak, items.count)
  }

  public func peek(_ n: Int) -> [Record] {
    lock.lock(); defer { lock.unlock() }
    return Array(items.prefix(n))
  }

  /// 只移除确实是开头这几条的记录（发送期间可能有新记录进来）。
  public func remove(ids: Set<String>) {
    lock.lock(); defer { lock.unlock() }
    items.removeAll { ids.contains($0.id) }
  }

  public var queuePeak: Int { lock.lock(); defer { lock.unlock() }; return peak }

  public var count: Int { lock.lock(); defer { lock.unlock() }; return items.count }
}

/// 屏幕文字里哪些不该读。
public enum ScreenTextPolicy {
  public static let wechat = "com.tencent.xinWeChat"

  /// 聊天软件的输入框是还没发出去的草稿：每打几个字就多一行，发出后又在聊天区重复一遍，
  /// 记下来只有噪声（2026-11-12 实测：微信一段里存了"我发现好事 / 我发现好像是做了 / 我下载了他们…"）。
  public static func skipsEditable(bundleID: String) -> Bool { bundleID == wechat }

  /// 开了微信对话就由它按会话拆消息；屏幕记录只留微信的使用时段，不再带微信窗口的文字。
  public static func keepsText(bundleID: String, wechatOn: Bool) -> Bool { !(bundleID == wechat && wechatOn) }
}
